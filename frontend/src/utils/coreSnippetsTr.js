const READABLE_ATTRIBUTES = ['placeholder', 'alt', 'title', 'aria-label', 'value']
const cache = new Map()

function swap(text) {
  const trimmed = text.trim()
  const turkish = CORE_SNIPPET_TR[trimmed]
  if (!turkish) return text
  const start = text.indexOf(trimmed)
  return text.slice(0, start) + turkish + text.slice(start + trimmed.length)
}

// The snippet with its readable words in Turkish. Markup, styles and anything
// the table does not know are left exactly as they were.
export function turkishSnippet(html) {
  if (typeof html !== 'string' || !html || typeof document === 'undefined') return html
  if (cache.has(html)) return cache.get(html)
  const template = document.createElement('template')
  template.innerHTML = html
  let changed = false
  const put = (before, after, write) => {
    if (after !== before) { write(after); changed = true }
  }
  const walk = (node) => {
    for (const child of node.childNodes) {
      if (child.nodeType === 3) {
        put(child.textContent, swap(child.textContent), (value) => { child.textContent = value })
      } else if (child.nodeType === 1 && child.tagName !== 'STYLE' && child.tagName !== 'SCRIPT') {
        for (const name of READABLE_ATTRIBUTES) {
          if (child.hasAttribute(name)) {
            put(child.getAttribute(name), swap(child.getAttribute(name)), (value) => child.setAttribute(name, value))
          }
        }
        walk(child)
      }
    }
  }
  walk(template.content)
  // Nothing to translate: the snippet exactly as written, not re-serialized.
  const out = changed ? template.innerHTML : html
  cache.set(html, out)
  return out
}
