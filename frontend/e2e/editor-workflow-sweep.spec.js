  const patched = (await api(request, 'PATCH', `/sites/${site.id}/`, { published: true })).data
  const submit = await request.post(`${API}/public/sites/${patched.slug}/submit/`, { data: { data: { name: 'Client Ada', message: 'Inbox workflow message' }, page: 'contact' } })
  expect(submit.status()).toBe(201)
  await request.post(`${API}/public/sites/${patched.slug}/view/`, { data: { path: '/', referrer: 'https://search.example.test/query' } })
  await api(request, 'POST', `/sites/${site.id}/share/`, { mode: 'link' })
