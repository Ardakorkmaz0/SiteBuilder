test('owner tools show failed row actions and allow a successful retry', async ({ page, request }) => {
  const { data: site } = await api(request, 'POST', '/sites/', { title: 'E2E tools retry' })
  const patched = (await api(request, 'PATCH', `/sites/${site.id}/`, { published: true })).data
  await request.post(`${API}/public/sites/${patched.slug}/submit/`, { data: { data: { message: 'Retry this inbox message' }, page: 'contact' } })
  await openEditor(page, site.id)
  await more(page, 'Site control center')
  await center(page).getByRole('button', { name: 'Inbox', exact: true }).click()
  await expect(center(page).getByText('Retry this inbox message', { exact: true })).toBeVisible()
  const route = `**/api/sites/${site.id}/submissions/*/`
  await page.route(route, (requestRoute) => requestRoute.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Inbox unavailable; try again.' }) }))
  await center(page).getByRole('button', { name: 'Mark read', exact: true }).click()
  await expect(center(page).getByRole('alert')).toContainText('Inbox unavailable; try again.')
  await expect(center(page).getByRole('button', { name: 'Mark read', exact: true })).toBeEnabled()
  await page.unroute(route)
  await center(page).getByRole('button', { name: 'Mark read', exact: true }).click()
  await expect(center(page).getByRole('button', { name: 'Mark unread', exact: true })).toBeVisible()
  await expect(center(page).getByRole('alert')).toHaveCount(0)
  await api(request, 'DELETE', `/sites/${site.id}/`)
})
